/** Isolated local integration test; email traffic is intercepted, never sent. */
import "dotenv/config";
import assert from "node:assert/strict";
import { randomBytes } from "node:crypto";
import { once } from "node:events";
import { createServer } from "node:http";
import express from "express";
import session from "express-session";
import pg from "pg";
import path from "node:path";

const url = new URL(process.env.DATABASE_URL ?? "");
assert.ok(["localhost", "127.0.0.1", "[::1]"].includes(url.hostname), "Only local PostgreSQL is allowed");
const control = new pg.Pool({ connectionString: url.toString() });
const schema = `training_test_${randomBytes(8).toString("hex")}`;
await control.query(`CREATE SCHEMA ${schema}`);
url.searchParams.set("options", `-c search_path=${schema}`);
process.env.DATABASE_URL = url.toString();
process.env.RESEND_API_KEY = "re_local_test_only";
process.env.BFV_URL = "";
const originalFetch = globalThis.fetch;
const emails: any[] = [];
let failFeedback = false;
globalThis.fetch = async (input, init) => {
  if (String(input).startsWith("https://api.resend.com/")) {
    const body = JSON.parse(String(init?.body));
    emails.push(body);
    const fail = failFeedback && JSON.stringify(body.to).includes("coach@example.invalid");
    return new Response(JSON.stringify(fail ? { name: "validation_error", message: "Fixture failure", statusCode: 422 } : { id: "fixture-mail" }), { status: fail ? 422 : 200, headers: { "Content-Type": "application/json" } });
  }
  return originalFetch(input, init);
};
let database: any;
const app = express();
const server = createServer(app);
try {
  database = (await import("../server/db")).db;
  await database.$client.query(`
    CREATE TABLE admin_settings (key VARCHAR(100) PRIMARY KEY, value TEXT NOT NULL);
    CREATE TABLE campaigns (id VARCHAR(36) PRIMARY KEY, password TEXT);
    CREATE TABLE festivals (id VARCHAR(36) PRIMARY KEY, password TEXT);
    CREATE TABLE calendar_events (LIKE public.calendar_events INCLUDING ALL);
    CREATE TABLE field_mappings (id VARCHAR(36) PRIMARY KEY DEFAULT gen_random_uuid(), team TEXT, event_type TEXT, default_field TEXT);
    CREATE TABLE event_requests (LIKE public.event_requests INCLUDING ALL);
    ALTER TABLE event_requests ADD COLUMN IF NOT EXISTS contact_email VARCHAR(255), ADD COLUMN IF NOT EXISTS contact_phone VARCHAR(40), ADD COLUMN IF NOT EXISTS rejection_reason TEXT;
  `);
  await database.$client.query("INSERT INTO admin_settings VALUES ('admin_password', 'training-preview-password')");
  app.use(express.json());
  app.use(session({ secret: randomBytes(32).toString("hex"), resave: false, saveUninitialized: false }));
  const { registerRoutes } = await import("../server/routes");
  await registerRoutes(server, app);
  app.use(express.static(path.resolve("dist/public")));
  app.get("/{*path}", (_req, res) => res.sendFile(path.resolve("dist/public/index.html")));
  server.listen(process.argv.includes("--preview") ? 3003 : 0, "127.0.0.1");
  await once(server, "listening");
  const address = server.address();
  assert.ok(address && typeof address !== "string");
  const base = `http://127.0.0.1:${address.port}`;
  let cookie = "";
  async function call(route: string, method = "GET", body?: unknown, admin = false) {
    const response = await fetch(base + route, { method, headers: { "Content-Type": "application/json", ...(admin && cookie ? { Cookie: cookie } : {}) }, body: body === undefined ? undefined : JSON.stringify(body) });
    if (admin && response.headers.get("set-cookie")) cookie = response.headers.get("set-cookie")!.split(";")[0];
    return { status: response.status, data: await response.json() };
  }
  assert.equal((await call("/api/auth/setup", "POST", { name: "Preview Admin", email: "admin@example.invalid", password: "training-preview-password", bootstrapPassword: "training-preview-password" }, true)).status, 201);
  const today = new Intl.DateTimeFormat("sv-SE", { timeZone: "Europe/Berlin" }).format(new Date());
  const first = new Date(`${today}T12:00:00Z`);
  const second = new Date(first); second.setUTCDate(second.getUTCDate() + 7);
  const berlinHour = (date: Date) => Number(new Intl.DateTimeFormat("en-GB", { timeZone: "Europe/Berlin", hour: "2-digit", hourCycle: "h23" }).format(date));
  second.setUTCHours(second.getUTCHours() + berlinHour(first) - berlinHour(second));
  const input = { type: "training", title: "C-Jugend Training", createdBy: "Fixture Coach", contactEmail: "coach@example.invalid", contactPhone: "+49 171 1234567", team: "c-jugend", pitch: "a-platz", startAt: first.toISOString(), endAt: new Date(first.getTime() + 3600000).toISOString() };
  assert.equal((await call("/api/public/event-requests", "POST", { ...input, contactEmail: undefined })).status, 201);
  assert.equal((await call("/api/public/event-requests", "POST", { ...input, contactEmail: "bad" })).status, 400);
  const created = await call("/api/public/event-requests", "POST", input);
  assert.equal(created.status, 201);
  const id = created.data.id;
  assert.equal((await call(`/api/admin/event-requests/${id}/approve`, "POST", {})).status, 401);
  const approved = await call(`/api/admin/event-requests/${id}/approve`, "POST", { pitch: "b-platz", adminNote: "Bitte auf dem B-Platz trainieren." }, true);
  assert.equal(approved.status, 200);
  assert.equal(approved.data.emailDelivery, "sent", "email has priority when both contact methods exist");
  assert.equal(approved.data.request.contactEmail, input.contactEmail);
  const feedback = emails.filter(mail => JSON.stringify(mail.to).includes("coach@example.invalid"));
  assert.equal(feedback.length, 1);
  assert.match(feedback[0].subject, /angenommen/);
  assert.match(feedback[0].text, /B-Platz/);
  assert.equal((await call(`/api/admin/event-requests/${id}/approve`, "POST", { pitch: "b-platz" }, true)).data.emailDelivery, "unchanged");
  assert.equal(emails.filter(mail => JSON.stringify(mail.to).includes("coach@example.invalid")).length, 1, "repeated approval does not send a duplicate");
  const next = await call("/api/public/event-requests", "POST", { ...input, startAt: second.toISOString(), endAt: new Date(second.getTime() + 3600000).toISOString() });
  await call(`/api/admin/event-requests/${next.data.id}/approve`, "POST", { pitch: "b-platz" }, true);
  const schedule = await call("/api/public/training-schedule");
  assert.equal(schedule.status, 200);
  assert.equal(schedule.data.slots.length, 1);
  assert.equal(schedule.data.slots[0].dates.length, 2);
  assert.ok(!JSON.stringify(schedule.data).includes("coach@example.invalid"));
  assert.ok(!JSON.stringify(schedule.data).includes("Bitte auf dem B-Platz"));
  const reject = await call("/api/public/event-requests", "POST", input);
  assert.equal((await call(`/api/admin/event-requests/${reject.data.id}`, "PATCH", { status: "rejected" }, true)).status, 400, "status changes cannot bypass the reason and notification workflow");
  assert.equal((await call(`/api/admin/event-requests/${reject.data.id}/reject`, "POST", {}, true)).status, 400, "a reason is required");
  assert.equal((await call(`/api/admin/event-requests/${reject.data.id}/reject`, "POST", { rejectionReason: "   " }, true)).status, 400);
  const rejected = await call(`/api/admin/event-requests/${reject.data.id}/reject`, "POST", { rejectionReason: "Platz belegt", adminNote: "Nur interne Notiz" }, true);
  assert.equal(rejected.data.emailDelivery, "sent");
  const rejectionMail = emails.filter(mail => JSON.stringify(mail.to).includes("coach@example.invalid")).at(-1);
  assert.match(rejectionMail.subject, /abgelehnt/);
  assert.match(rejectionMail.text, /Grund der Ablehnung: Platz belegt/);
  assert.ok(!rejectionMail.text.includes("Nur interne Notiz"));
  const { requestFeedback, requestFeedbackLinks } = await import("../shared/request-feedback");
  const draft = requestFeedback([rejected.data]);
  assert.match(draft.text, /Grund der Ablehnung: Platz belegt/);
  assert.ok(!draft.text.includes("Nur interne Notiz"));
  const links = requestFeedbackLinks([rejected.data], draft);
  assert.ok(links.mailto?.startsWith("mailto:coach%40example.invalid?"));
  assert.equal(rejected.data.rejectionReason, "Platz belegt");
  const { dbStorage } = await import("../server/dbStorage");
  const legacy = await dbStorage.createEventRequest({ ...input, contactEmail: undefined, contactPhone: undefined });
  assert.equal((await call(`/api/admin/event-requests/${legacy.id}/reject`, "POST", { rejectionReason: "Platz belegt" }, true)).data.emailDelivery, "not-requested");
  const phoneOnly = await call("/api/public/event-requests", "POST", { ...input, contactEmail: undefined, contactPhone: "+49 (841) 1234567" });
  assert.equal(phoneOnly.status, 201);
  assert.equal(phoneOnly.data.contactPhone, "+49 (841) 1234567");
  const mailCount = emails.length;
  assert.equal((await call(`/api/admin/event-requests/${phoneOnly.data.id}/reject`, "POST", { rejectionReason: "Telefonische Rückmeldung: Platz belegt" }, true)).data.emailDelivery, "manual");
  assert.equal(emails.length, mailCount, "phone-only decisions trigger no automatic message");
  const game = await call("/api/public/event-requests", "POST", { ...input, type: "spiel", title: "C-Jugend Spiel", contactEmail: undefined });
  assert.equal(game.status, 201);
  const acceptedGame = await call(`/api/admin/event-requests/${game.data.id}/approve`, "POST", { force: true }, true);
  assert.equal(acceptedGame.status, 200);
  assert.equal(acceptedGame.data.event.type, "spiel");
  assert.equal(acceptedGame.data.emailDelivery, "manual");
  const publicCalendar = await call(`/api/public/calendar/fields?startDate=${today}&endDate=${today}`);
  assert.equal(publicCalendar.status, 200);
  assert.ok(!JSON.stringify(publicCalendar.data).includes("+49 (841) 1234567"));
  failFeedback = true;
  const failureRequest = await call("/api/public/event-requests", "POST", input);
  const failure = await call(`/api/admin/event-requests/${failureRequest.data.id}/reject`, "POST", { rejectionReason: "Platz belegt" }, true);
  assert.equal(failure.status, 200);
  assert.equal(failure.data.status, "rejected");
  assert.equal(failure.data.emailDelivery, "failed", "provider errors are surfaced without undoing the decision");
  console.log("Training integration passed: automatic email with priority, rejection reason, manual phone-only feedback, duplicate protection, provider failure, privacy and permissions.");
  if (process.argv.includes("--preview")) {
    console.log(`Fixture preview: ${base}/trainingszeiten (temporary test data, email intercepted)`);
    await new Promise<void>(resolve => { process.once("SIGTERM", resolve); process.once("SIGINT", resolve); });
  }
} finally {
  globalThis.fetch = originalFetch;
  server.closeAllConnections();
  if (server.listening) await new Promise<void>(resolve => server.close(() => resolve()));
  if (database) await database.$client.end();
  await control.query(`DROP SCHEMA ${schema} CASCADE`);
  await control.end();
}
